BEGIN;

CREATE TABLE IF NOT EXISTS public."warningIcons" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warning_header varchar NOT NULL,
    source_url text NOT NULL,
    icon bytea NOT NULL,
    content_type varchar NOT NULL DEFAULT 'image/svg+xml',
    sample_barcode varchar,
    downloaded_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT warning_icons_header_url_unique UNIQUE (warning_header, source_url)
);

CREATE INDEX IF NOT EXISTS warning_icons_header_idx
    ON public."warningIcons" (warning_header);

COMMENT ON TABLE public."warningIcons" IS
    'Locally cached medication warning icons, linked to warning headers and their source variants.';
COMMENT ON COLUMN public."warningIcons".sample_barcode IS
    'Representative barcode row from which the warning header and source URL were selected.';

COMMIT;
