BEGIN;

-- Operational İTS Takas remains serialized and continues to use takasQrItems.
-- Historical Farmassist Takas can also contain cosmetics and other
-- non-serialized units, so preserve those units without inventing QR fields.
CREATE TABLE IF NOT EXISTS public."takasBarcodeItems" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    takas_id integer NOT NULL REFERENCES public.takas(record_id) ON DELETE CASCADE,
    barcode varchar NOT NULL,
    entry_cost numeric(12,2),
    debt_amount numeric(12,2) NOT NULL CHECK (debt_amount >= 0),
    status varchar NOT NULL DEFAULT 'accepted',
    CONSTRAINT ck_takasBarcodeItems_status CHECK (status IN (
        'pending_transfer', 'in_transit', 'accepted',
        'transfer_cancelled', 'transfer_failed', 'reconciliation_required'))
);

CREATE INDEX IF NOT EXISTS "ix_takasBarcodeItems_takas_status"
    ON public."takasBarcodeItems"(takas_id, status);
CREATE INDEX IF NOT EXISTS "ix_takasBarcodeItems_barcode"
    ON public."takasBarcodeItems"(barcode);

CREATE TABLE IF NOT EXISTS public.farmassist_takas_import_map (
    source_table varchar NOT NULL,
    source_takas_id integer NOT NULL,
    target_takas_id integer NOT NULL UNIQUE
        REFERENCES public.takas(record_id) ON DELETE CASCADE,
    source_fingerprint char(64) NOT NULL,
    imported_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (source_table, source_takas_id),
    CONSTRAINT ck_farmassist_takas_source_table CHECK (
        source_table IN ('dbo.Takas', 'dbo.GunlukTakas'))
);

COMMIT;
