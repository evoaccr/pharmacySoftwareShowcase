BEGIN;

CREATE TABLE IF NOT EXISTS public."salesRefunds" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer REFERENCES public.patient (record_id),
    total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0),
    payement_finished boolean NOT NULL DEFAULT FALSE,
    user_no varchar REFERENCES public.users (user_id),
    "timestamp" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public."salesRefundPayements" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id integer NOT NULL REFERENCES public."salesRefunds" (record_id) ON DELETE CASCADE,
    payment_type smallint NOT NULL REFERENCES public."payementTypes" (record_id),
    amount numeric(12,2) NOT NULL CHECK (amount > 0),
    CONSTRAINT ck_salesRefundPayements_supported_type CHECK (payment_type IN (1, 2, 3))
);

CREATE INDEX IF NOT EXISTS ix_salesRefunds_patient_timestamp
    ON public."salesRefunds" (patient_id, "timestamp" DESC);
CREATE INDEX IF NOT EXISTS ix_salesRefundPayements_refund_id
    ON public."salesRefundPayements" (refund_id);

CREATE OR REPLACE FUNCTION public.pharmacy_refresh_refund_payment_status(target_refund_id integer)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    refund_total numeric(12,2);
    paid_total numeric(12,2);
BEGIN
    SELECT total_amount
    INTO refund_total
    FROM public."salesRefunds"
    WHERE record_id = target_refund_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT COALESCE(SUM(amount), 0)
    INTO paid_total
    FROM public."salesRefundPayements"
    WHERE refund_id = target_refund_id;

    UPDATE public."salesRefunds"
    SET payement_finished = paid_total >= refund_total
    WHERE record_id = target_refund_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.pharmacy_apply_refund_payment_status()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.refund_id IS DISTINCT FROM NEW.refund_id THEN
        PERFORM public.pharmacy_refresh_refund_payment_status(OLD.refund_id);
    END IF;
    PERFORM public.pharmacy_refresh_refund_payment_status(
        CASE WHEN TG_OP = 'DELETE' THEN OLD.refund_id ELSE NEW.refund_id END);
    RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_salesRefundPayements_refresh_refund ON public."salesRefundPayements";
CREATE TRIGGER trg_salesRefundPayements_refresh_refund
AFTER INSERT OR UPDATE OR DELETE ON public."salesRefundPayements"
FOR EACH ROW
EXECUTE FUNCTION public.pharmacy_apply_refund_payment_status();

-- Older retail-sale movements did not persist their exit price. Preserve the
-- best available price now so those sold QR codes can participate in refunds.
UPDATE public."qrInactive" inactive
SET exit_price = COALESCE(price.sale_price, price.public_price, price.public_paid_price, 0)
FROM public.barcode product
LEFT JOIN public."barcodePrices" price ON price.record_reference_no = product.record_id
WHERE inactive.exit_price IS NULL
  AND inactive.barcode = product.barcode
  AND EXISTS (
      SELECT 1
      FROM public."qrMovements" movement
      JOIN public."qrMovementTypes" type ON type.record_id = movement.movement_type
      WHERE movement.qr_code = inactive.qr_code
        AND type.code = 'PERAK_OUT');

COMMIT;
