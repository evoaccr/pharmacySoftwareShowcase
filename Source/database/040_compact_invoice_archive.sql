BEGIN;

LOCK TABLE public.invoice_lines, public.invoices, public.addresses IN ACCESS EXCLUSIVE MODE;

CREATE TABLE public.addresses_compact (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    party_name text NOT NULL DEFAULT '',
    identity_no text NOT NULL DEFAULT ''
);

INSERT INTO public.addresses_compact (record_id, party_name, identity_no)
OVERRIDING SYSTEM VALUE
SELECT
    record_id,
    party_name,
    COALESCE(
        (regexp_match(tckn, '(^|[^0-9])([0-9]{11})([^0-9]|$)'))[2],
        (regexp_match(vkn, '(^|[^0-9])([0-9]{10})([^0-9]|$)'))[2],
        '')
FROM public.addresses;

SELECT setval(
    pg_get_serial_sequence('public.addresses_compact', 'record_id'),
    GREATEST(COALESCE((SELECT max(record_id) FROM public.addresses_compact), 0), 1),
    EXISTS (SELECT 1 FROM public.addresses_compact));

CREATE TEMPORARY TABLE invoice_migration_selection ON COMMIT DROP AS
SELECT DISTINCT ON (ettn)
    record_id,
    ettn AS invoice_uuid
FROM public.invoices
WHERE portal_type_key IN ('incoming-invoice', 'outgoing-invoice', 'archive-invoice')
  AND trim(ettn) <> ''
ORDER BY ettn, imported_at DESC, version_no DESC, record_id DESC;

CREATE TABLE public.invoices_compact (
    invoice_uuid text PRIMARY KEY,
    invoice_type text NOT NULL,
    sender_address_id integer NOT NULL REFERENCES public.addresses_compact(record_id),
    receiver_address_id integer NOT NULL REFERENCES public.addresses_compact(record_id),
    issue_date date,
    due_date date,
    database_entry_at timestamp with time zone NOT NULL DEFAULT now(),
    total_cost numeric(18,4),
    discount_amount numeric(18,4),
    kdv_amount numeric(18,4),
    payable_amount numeric(18,4),
    CONSTRAINT invoices_compact_type_check CHECK (
        invoice_type IN ('Gelen Fatura', 'Giden Fatura', 'E-Arşiv Fatura'))
);

INSERT INTO public.invoices_compact (
    invoice_uuid,
    invoice_type,
    sender_address_id,
    receiver_address_id,
    issue_date,
    due_date,
    database_entry_at,
    total_cost,
    discount_amount,
    kdv_amount,
    payable_amount)
SELECT
    selection.invoice_uuid,
    CASE invoice.portal_type_key
        WHEN 'incoming-invoice' THEN 'Gelen Fatura'
        WHEN 'outgoing-invoice' THEN 'Giden Fatura'
        WHEN 'archive-invoice' THEN 'E-Arşiv Fatura'
    END,
    invoice.invoice_from_address_id,
    invoice.invoice_to_address_id,
    invoice.issue_date,
    invoice.due_date,
    invoice.imported_at,
    COALESCE(invoice.line_extension_amount, invoice.tax_exclusive_amount),
    COALESCE(line_totals.discount_amount, 0),
    invoice.tax_amount,
    invoice.payable_amount
FROM invoice_migration_selection selection
JOIN public.invoices invoice ON invoice.record_id = selection.record_id
LEFT JOIN LATERAL (
    SELECT sum(COALESCE(line.discount_amount, 0)) AS discount_amount
    FROM public.invoice_lines line
    WHERE line.invoice_id = invoice.record_id
) line_totals ON true;

CREATE TABLE public.invoice_lines_compact (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_uuid text NOT NULL REFERENCES public.invoices_compact(invoice_uuid) ON DELETE CASCADE,
    line_number integer NOT NULL,
    item_code text NOT NULL DEFAULT '',
    barcode text NOT NULL DEFAULT '',
    item_name text NOT NULL DEFAULT '',
    description text NOT NULL DEFAULT '',
    quantity numeric(18,4),
    unit text NOT NULL DEFAULT '',
    unit_price numeric(18,4),
    vat_rate numeric(9,4),
    vat_amount numeric(18,4),
    discount_amount numeric(18,4),
    line_amount numeric(18,4),
    currency text NOT NULL DEFAULT '',
    is_medication boolean NOT NULL,
    raw_data jsonb NOT NULL DEFAULT '{}'::jsonb
);

INSERT INTO public.invoice_lines_compact (
    record_id,
    invoice_uuid,
    line_number,
    item_code,
    barcode,
    item_name,
    description,
    quantity,
    unit,
    unit_price,
    vat_rate,
    vat_amount,
    discount_amount,
    line_amount,
    currency,
    is_medication,
    raw_data)
OVERRIDING SYSTEM VALUE
SELECT
    line.record_id,
    selection.invoice_uuid,
    line.line_number,
    line.item_code,
    line.barcode,
    line.item_name,
    line.description,
    line.quantity,
    line.unit,
    line.unit_price,
    line.vat_rate,
    line.vat_amount,
    line.discount_amount,
    line.line_amount,
    line.currency,
    line.is_medication,
    line.raw_data
FROM public.invoice_lines line
JOIN invoice_migration_selection selection ON selection.record_id = line.invoice_id;

SELECT setval(
    pg_get_serial_sequence('public.invoice_lines_compact', 'record_id'),
    GREATEST(COALESCE((SELECT max(record_id) FROM public.invoice_lines_compact), 0), 1),
    EXISTS (SELECT 1 FROM public.invoice_lines_compact));

DROP TABLE public.invoice_lines;
DROP TABLE public.invoices;
DROP TABLE public.addresses;

ALTER TABLE public.addresses_compact RENAME TO addresses;
ALTER TABLE public.invoices_compact RENAME TO invoices;
ALTER TABLE public.invoice_lines_compact RENAME TO invoice_lines;

ALTER TABLE public.invoices RENAME CONSTRAINT invoices_compact_type_check TO invoices_type_check;

CREATE INDEX invoices_type_issue_date_idx ON public.invoices(invoice_type, issue_date);
CREATE INDEX invoices_sender_address_idx ON public.invoices(sender_address_id);
CREATE INDEX invoices_receiver_address_idx ON public.invoices(receiver_address_id);
CREATE INDEX invoice_lines_invoice_uuid_idx ON public.invoice_lines(invoice_uuid);
CREATE INDEX addresses_party_name_idx ON public.addresses(party_name);
CREATE INDEX addresses_identity_no_idx ON public.addresses(identity_no);

COMMIT;
