BEGIN;

UPDATE public.pharmacy
SET debt_balance = 0
WHERE debt_balance IS NULL;

ALTER TABLE public.pharmacy
    ALTER COLUMN debt_balance TYPE numeric(12,2)
        USING ROUND(COALESCE(debt_balance, 0)::numeric, 2),
    ALTER COLUMN debt_balance SET DEFAULT 0,
    ALTER COLUMN debt_balance SET NOT NULL;

CREATE TABLE IF NOT EXISTS public.takas (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pharmacy_id integer NOT NULL REFERENCES public.pharmacy(record_id),
    direction varchar NOT NULL DEFAULT 'outgoing',
    source_gln varchar(13) NOT NULL,
    destination_gln varchar(13) NOT NULL,
    status varchar NOT NULL DEFAULT 'pending_transfer',
    debt_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (debt_amount >= 0),
    transfer_notification_id varchar(20),
    accept_notification_id varchar(20),
    cancel_notification_id varchar(20),
    user_no varchar REFERENCES public.users(user_id),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    transferred_at timestamp without time zone,
    accepted_at timestamp without time zone,
    cancelled_at timestamp without time zone,
    debt_applied_at timestamp without time zone,
    debt_reversed_at timestamp without time zone,
    last_status_checked_at timestamp without time zone,
    next_status_check_at timestamp without time zone,
    status_check_attempts integer NOT NULL DEFAULT 0 CHECK (status_check_attempts >= 0),
    last_status_error text,
    notes text,
    CONSTRAINT ck_takas_direction CHECK (direction IN ('outgoing', 'incoming')),
    CONSTRAINT ck_takas_status CHECK (status IN (
        'pending_transfer', 'in_transit', 'partially_transferred',
        'partially_accepted', 'accepted', 'partially_cancelled',
        'cancelled', 'failed', 'reconciliation_required')),
    CONSTRAINT ck_takas_source_gln CHECK (source_gln ~ '^[0-9]{13}$'),
    CONSTRAINT ck_takas_destination_gln CHECK (destination_gln ~ '^[0-9]{13}$'),
    CONSTRAINT ck_takas_distinct_gln CHECK (source_gln <> destination_gln)
);

CREATE TABLE IF NOT EXISTS public."takasQrItems" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    takas_id integer NOT NULL REFERENCES public.takas(record_id) ON DELETE CASCADE,
    qr_code varchar NOT NULL,
    barcode varchar NOT NULL,
    gtin varchar(14) NOT NULL,
    serial_number varchar(20) NOT NULL,
    batch_number varchar(20) NOT NULL,
    expiry_date date NOT NULL,
    entry_cost numeric(12,2),
    debt_amount numeric(12,2) NOT NULL CHECK (debt_amount >= 0),
    status varchar NOT NULL DEFAULT 'pending_transfer',
    transfer_result_code varchar(5),
    accept_result_code varchar(5),
    cancel_result_code varchar(5),
    last_status_result_code varchar(5),
    last_status_gln1 varchar(13),
    last_status_gln2 varchar(13),
    last_checked_at timestamp without time zone,
    status_changed_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error text,
    CONSTRAINT uq_takasQrItems_takas_qr UNIQUE (takas_id, qr_code),
    CONSTRAINT ck_takasQrItems_gtin CHECK (gtin ~ '^[0-9]{14}$'),
    CONSTRAINT ck_takasQrItems_status CHECK (status IN (
        'pending_transfer', 'in_transit', 'accepted',
        'transfer_cancelled', 'transfer_failed', 'reconciliation_required'))
);

CREATE TABLE IF NOT EXISTS public."qrHanged" (
    qr_code varchar PRIMARY KEY,
    takas_item_id integer NOT NULL UNIQUE REFERENCES public."takasQrItems"(record_id),
    barcode varchar NOT NULL,
    expiry_date date,
    entry_cost numeric(12,2),
    debt_amount numeric(12,2) NOT NULL CHECK (debt_amount >= 0),
    reference_no varchar NOT NULL,
    hanged_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_takas_pharmacy_created
    ON public.takas(pharmacy_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_takas_status_next_check
    ON public.takas(status, next_status_check_at)
    WHERE status IN ('in_transit', 'partially_transferred', 'partially_accepted', 'reconciliation_required');
CREATE INDEX IF NOT EXISTS "ix_takasQrItems_takas_status"
    ON public."takasQrItems"(takas_id, status);
CREATE INDEX IF NOT EXISTS "ix_takasQrItems_qr_code"
    ON public."takasQrItems"(qr_code);
CREATE UNIQUE INDEX IF NOT EXISTS "uq_takasQrItems_unresolved_qr"
    ON public."takasQrItems"(qr_code)
    WHERE status IN ('pending_transfer', 'in_transit', 'reconciliation_required');
CREATE INDEX IF NOT EXISTS "ix_qrHanged_barcode"
    ON public."qrHanged"(barcode);

CREATE OR REPLACE FUNCTION public.pharmacy_apply_qr_movement()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    active_row public."qrActive"%ROWTYPE;
    inactive_row public."qrInactive"%ROWTYPE;
    movement_code varchar;
    barcode_only varchar;
    parsed_barcode varchar;
    parsed_expiry date;
    inserted_count integer;
    takas_item_id integer;
    takas_item_debt numeric(12,2);
BEGIN
    SELECT code INTO STRICT movement_code
    FROM public."qrMovementTypes"
    WHERE record_id = NEW.movement_type;

    SELECT b.barcode INTO barcode_only
    FROM public.barcode b
    WHERE b.barcode = NEW.qr_code
    LIMIT 1;

    IF barcode_only IS NOT NULL THEN
        IF movement_code = 'TRANSF_OUT' THEN
            RAISE EXCEPTION 'Takas çıkışı tekil ilaç karekodu gerektirir: %', barcode_only
                USING ERRCODE = '22023';
        ELSIF movement_code IN (
            'DEP_IN', 'FIRM_IN', 'TRANSF_IN', 'PERAK_RETURN',
            'PRESC_RETURN', 'MAN_IN', 'QR_ADD'
        ) THEN
            INSERT INTO public."barcodeActive" (barcode, quantity)
            VALUES (barcode_only, 1)
            ON CONFLICT (barcode) DO UPDATE
            SET quantity = public."barcodeActive".quantity + 1;
        ELSIF movement_code IN (
            'DEP_RETURN', 'FIRM_RETURN', 'PERAK_OUT',
            'PRESC_OUT', 'DESTRUCTION', 'MAN_OUT'
        ) THEN
            UPDATE public."barcodeActive"
            SET quantity = quantity - 1
            WHERE barcode = barcode_only
              AND quantity > 0;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'Barkod aktif stokta bulunamadı veya miktarı sıfır: %', barcode_only
                    USING ERRCODE = 'P0002';
            END IF;
        END IF;
        RETURN NEW;
    END IF;

    IF movement_code IN (
        'DEP_IN', 'FIRM_IN', 'TRANSF_IN', 'PERAK_RETURN',
        'PRESC_RETURN', 'MAN_IN', 'QR_ADD'
    ) THEN
        SELECT * INTO inactive_row
        FROM public."qrInactive"
        WHERE qr_code = NEW.qr_code
        FOR UPDATE;

        parsed_barcode := COALESCE(inactive_row.barcode, public.pharmacy_qr_barcode(NEW.qr_code));
        parsed_expiry := COALESCE(inactive_row.expiry_date, public.pharmacy_qr_expiry(NEW.qr_code));

        IF parsed_barcode IS NULL THEN
            RAISE EXCEPTION 'Karekoddan barkod bilgisi okunamadı.'
                USING ERRCODE = '22023';
        END IF;

        INSERT INTO public."qrActive" (
            qr_code, barcode, expiry_date, status, purchase_cost, reference_no
        ) VALUES (
            NEW.qr_code, parsed_barcode, parsed_expiry, NULL,
            inactive_row.entry_cost, NEW.reference_code
        )
        ON CONFLICT (qr_code) DO NOTHING;
        GET DIAGNOSTICS inserted_count = ROW_COUNT;

        IF inserted_count = 0 THEN
            RAISE EXCEPTION 'Karekod zaten aktif stokta: %', NEW.qr_code
                USING ERRCODE = '23505';
        END IF;

        DELETE FROM public."qrInactive" WHERE qr_code = NEW.qr_code;
        PERFORM public.pharmacy_refresh_barcode_active(parsed_barcode);
        RETURN NEW;
    END IF;

    IF movement_code = 'TRANSF_OUT' THEN
        SELECT item.record_id, item.debt_amount
        INTO takas_item_id, takas_item_debt
        FROM public."takasQrItems" item
        JOIN public.takas transfer ON transfer.record_id = item.takas_id
        WHERE item.qr_code = NEW.qr_code
          AND NEW.reference_code = 'T' || transfer.record_id::text
          AND item.status = 'pending_transfer'
        FOR UPDATE OF item;

        IF takas_item_id IS NULL THEN
            RAISE EXCEPTION 'Takas hareketi için bekleyen karekod satırı bulunamadı: %', NEW.qr_code
                USING ERRCODE = 'P0002';
        END IF;

        SELECT * INTO active_row
        FROM public."qrActive"
        WHERE qr_code = NEW.qr_code
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Karekod aktif stokta bulunamadı: %', NEW.qr_code
                USING ERRCODE = 'P0002';
        END IF;

        INSERT INTO public."qrHanged" (
            qr_code, takas_item_id, barcode, expiry_date,
            entry_cost, debt_amount, reference_no
        ) VALUES (
            active_row.qr_code, takas_item_id, active_row.barcode, active_row.expiry_date,
            active_row.purchase_cost, takas_item_debt, NEW.reference_code
        );

        DELETE FROM public."qrActive" WHERE qr_code = NEW.qr_code;
        PERFORM public.pharmacy_refresh_barcode_active(active_row.barcode);
        RETURN NEW;
    END IF;

    IF movement_code IN (
        'DEP_RETURN', 'FIRM_RETURN', 'PERAK_OUT',
        'PRESC_OUT', 'DESTRUCTION', 'MAN_OUT'
    ) THEN
        SELECT * INTO active_row
        FROM public."qrActive"
        WHERE qr_code = NEW.qr_code
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Karekod aktif stokta bulunamadı: %', NEW.qr_code
                USING ERRCODE = 'P0002';
        END IF;

        INSERT INTO public."qrInactive" (
            qr_code, barcode, expiry_date, entry_cost, exit_price, reference_no
        ) VALUES (
            active_row.qr_code, active_row.barcode, active_row.expiry_date,
            active_row.purchase_cost, NULL, NEW.reference_code
        )
        ON CONFLICT (qr_code) DO UPDATE
        SET barcode = EXCLUDED.barcode,
            expiry_date = EXCLUDED.expiry_date,
            entry_cost = EXCLUDED.entry_cost,
            exit_price = EXCLUDED.exit_price,
            reference_no = EXCLUDED.reference_no;

        DELETE FROM public."qrActive" WHERE qr_code = NEW.qr_code;
        PERFORM public.pharmacy_refresh_barcode_active(active_row.barcode);
        RETURN NEW;
    END IF;

    SELECT * INTO active_row
    FROM public."qrActive"
    WHERE qr_code = NEW.qr_code
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Karekod aktif stokta bulunamadı: %', NEW.qr_code
            USING ERRCODE = 'P0002';
    END IF;

    UPDATE public."qrActive"
    SET status = CASE movement_code
        WHEN 'QUAR_IN' THEN 'QUARANTINE'
        WHEN 'QUAR_OUT' THEN NULL
        WHEN 'RECALL' THEN 'RECALLED'
        WHEN 'RESERVED' THEN 'RESERVED'
        WHEN 'DAMAGED' THEN 'DAMAGED'
        ELSE status
    END,
    reference_no = COALESCE(NEW.reference_code, reference_no)
    WHERE qr_code = NEW.qr_code;

    RETURN NEW;
END;
$$;

COMMIT;
