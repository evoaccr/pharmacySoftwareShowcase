BEGIN;

ALTER TABLE public."salesRefunds"
    ADD COLUMN IF NOT EXISTS discount_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    ADD COLUMN IF NOT EXISTS debt_reduction_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (debt_reduction_amount >= 0);

CREATE TABLE IF NOT EXISTS public."salesQrItems" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id integer NOT NULL REFERENCES public.sales (record_id) ON DELETE CASCADE,
    qr_code varchar NOT NULL,
    barcode varchar NOT NULL,
    gross_price numeric(12,2) NOT NULL CHECK (gross_price >= 0),
    discount_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0 AND discount_amount <= gross_price),
    exit_price numeric(12,2) NOT NULL CHECK (exit_price >= 0),
    entry_cost numeric(12,2)
);

CREATE TABLE IF NOT EXISTS public."salesRefundItems" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id integer NOT NULL REFERENCES public."salesRefunds" (record_id) ON DELETE CASCADE,
    original_sale_id integer NOT NULL REFERENCES public.sales (record_id),
    qr_code varchar NOT NULL,
    barcode varchar NOT NULL,
    gross_price numeric(12,2) NOT NULL CHECK (gross_price >= 0),
    discount_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0 AND discount_amount <= gross_price),
    exit_price numeric(12,2) NOT NULL CHECK (exit_price >= 0),
    entry_cost numeric(12,2)
);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'ck_salesQrItems_net_exit_price') THEN
        ALTER TABLE public."salesQrItems"
            ADD CONSTRAINT "ck_salesQrItems_net_exit_price"
            CHECK (exit_price = gross_price - discount_amount);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'ck_salesRefundItems_net_exit_price') THEN
        ALTER TABLE public."salesRefundItems"
            ADD CONSTRAINT "ck_salesRefundItems_net_exit_price"
            CHECK (exit_price = gross_price - discount_amount);
    END IF;
END;
$$;

CREATE INDEX IF NOT EXISTS ix_salesQrItems_sale_id ON public."salesQrItems" (sale_id);
CREATE INDEX IF NOT EXISTS ix_salesQrItems_qr_code ON public."salesQrItems" (qr_code);
CREATE INDEX IF NOT EXISTS ix_salesRefundItems_refund_id ON public."salesRefundItems" (refund_id);
CREATE INDEX IF NOT EXISTS ix_salesRefundItems_qr_code ON public."salesRefundItems" (qr_code);

WITH movement_lines AS (
    SELECT movement.record_id AS movement_id,
           SUBSTRING(movement.reference_code FROM 2)::integer AS sale_id,
           movement.qr_code,
           COALESCE(inactive.barcode, active.barcode,
                    CASE WHEN movement.qr_code ~ '^[0-9]{8,14}$' THEN movement.qr_code
                         ELSE public.pharmacy_qr_barcode(movement.qr_code) END,
                    movement.qr_code) AS barcode,
           COALESCE(price.sale_price, price.public_price, price.public_paid_price, inactive.exit_price, 0)::numeric(12,2) AS gross_price,
           COALESCE(inactive.entry_cost, active.purchase_cost) AS entry_cost
    FROM public."qrMovements" movement
    JOIN public."qrMovementTypes" type ON type.record_id = movement.movement_type
    LEFT JOIN public."qrInactive" inactive ON inactive.qr_code = movement.qr_code
    LEFT JOIN public."qrActive" active ON active.qr_code = movement.qr_code
    LEFT JOIN public.barcode product ON product.barcode = COALESCE(
        inactive.barcode, active.barcode,
        CASE WHEN movement.qr_code ~ '^[0-9]{8,14}$' THEN movement.qr_code
             ELSE public.pharmacy_qr_barcode(movement.qr_code) END)
    LEFT JOIN public."barcodePrices" price ON price.record_reference_no = product.record_id
    WHERE type.code IN ('PERAK_OUT', 'PRESC_OUT')
      AND movement.reference_code ~ '^P[0-9]+$'
      AND NOT EXISTS (
          SELECT 1 FROM public."salesQrItems" existing
          WHERE existing.sale_id = SUBSTRING(movement.reference_code FROM 2)::integer
            AND existing.qr_code = movement.qr_code)
), discount_totals AS (
    SELECT payment.sale_id, COALESCE(SUM(payment.amount), 0)::numeric(12,2) AS discount_total
    FROM public."salesPayements" payment
    JOIN public."payementTypes" type ON type.record_id = payment.payment_type
    WHERE type.payment_type = 'discount'
    GROUP BY payment.sale_id
), weighted AS (
    SELECT line.*,
           COALESCE(discount.discount_total, 0) AS discount_total,
           ROUND(COALESCE(discount.discount_total, 0) * line.gross_price /
                 NULLIF(SUM(line.gross_price) OVER (PARTITION BY line.sale_id), 0), 2) AS allocated,
           ROW_NUMBER() OVER (PARTITION BY line.sale_id ORDER BY line.movement_id DESC) AS reverse_row
    FROM movement_lines line
    LEFT JOIN discount_totals discount ON discount.sale_id = line.sale_id
), finalized AS (
    SELECT weighted.*,
           CASE WHEN reverse_row = 1
                THEN allocated + discount_total - SUM(allocated) OVER (PARTITION BY sale_id)
                ELSE allocated END AS final_discount
    FROM weighted
)
INSERT INTO public."salesQrItems" (
    sale_id, qr_code, barcode, gross_price, discount_amount, exit_price, entry_cost)
SELECT sale_id, qr_code, barcode, gross_price,
       LEAST(gross_price, GREATEST(0, final_discount)),
       GREATEST(0, gross_price - LEAST(gross_price, GREATEST(0, final_discount))),
       entry_cost
FROM finalized
ORDER BY movement_id;

WITH return_lines AS (
    SELECT movement.record_id AS movement_id,
           SUBSTRING(movement.reference_code FROM 2)::integer AS refund_id,
           movement.qr_code,
           SUBSTRING(original.reference_code FROM 2)::integer AS original_sale_id
    FROM public."qrMovements" movement
    JOIN public."qrMovementTypes" type ON type.record_id = movement.movement_type
    JOIN LATERAL (
        SELECT earlier.reference_code
        FROM public."qrMovements" earlier
        JOIN public."qrMovementTypes" earlier_type ON earlier_type.record_id = earlier.movement_type
        WHERE earlier.qr_code = movement.qr_code
          AND earlier.record_id < movement.record_id
          AND earlier_type.code IN ('PERAK_OUT', 'PRESC_OUT')
          AND earlier.reference_code ~ '^P[0-9]+$'
        ORDER BY earlier.record_id DESC
        LIMIT 1
    ) original ON TRUE
    WHERE type.code IN ('PERAK_RETURN', 'PRESC_RETURN')
      AND movement.reference_code ~ '^R[0-9]+$'
)
INSERT INTO public."salesRefundItems" (
    refund_id, original_sale_id, qr_code, barcode, gross_price, discount_amount, exit_price, entry_cost)
SELECT line.refund_id, line.original_sale_id, line.qr_code, sold.barcode, sold.gross_price,
       sold.discount_amount, sold.exit_price, sold.entry_cost
FROM return_lines line
JOIN LATERAL (
    SELECT item.*
    FROM public."salesQrItems" item
    WHERE item.sale_id = line.original_sale_id
      AND item.qr_code = line.qr_code
    ORDER BY item.record_id DESC
    LIMIT 1
) sold ON TRUE
WHERE NOT EXISTS (
    SELECT 1 FROM public."salesRefundItems" existing
    WHERE existing.refund_id = line.refund_id
      AND existing.qr_code = line.qr_code);

UPDATE public."salesRefunds" refund
SET discount_amount = totals.discount_amount
FROM (
    SELECT refund_id, COALESCE(SUM(discount_amount), 0)::numeric(12,2) AS discount_amount
    FROM public."salesRefundItems"
    GROUP BY refund_id
) totals
WHERE totals.refund_id = refund.record_id;

UPDATE public."qrInactive" inactive
SET exit_price = (
        SELECT item.exit_price
        FROM public."salesQrItems" item
        WHERE item.qr_code = inactive.qr_code
        ORDER BY item.record_id DESC
        LIMIT 1),
    entry_cost = COALESCE((
        SELECT item.entry_cost
        FROM public."salesQrItems" item
        WHERE item.qr_code = inactive.qr_code
        ORDER BY item.record_id DESC
        LIMIT 1), inactive.entry_cost)
WHERE EXISTS (
    SELECT 1
    FROM public."salesQrItems" item
    WHERE item.qr_code = inactive.qr_code
);

CREATE OR REPLACE FUNCTION public.pharmacy_refresh_refund_payment_status(target_refund_id integer)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    refund_total numeric(12,2);
    debt_reduction numeric(12,2);
    paid_total numeric(12,2);
BEGIN
    SELECT total_amount, debt_reduction_amount
    INTO refund_total, debt_reduction
    FROM public."salesRefunds"
    WHERE record_id = target_refund_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT COALESCE(SUM(amount), 0)
    INTO paid_total
    FROM public."salesRefundPayements"
    WHERE refund_id = target_refund_id;

    UPDATE public."salesRefunds"
    SET payement_finished = paid_total = GREATEST(refund_total - debt_reduction, 0)
    WHERE record_id = target_refund_id;
END;
$$;

COMMIT;
