CREATE TABLE IF NOT EXISTS public.family_group (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_group_name varchar NOT NULL UNIQUE,
    main_patient_id integer REFERENCES public.patient(record_id) ON DELETE SET NULL,
    member_ids integer[] NOT NULL DEFAULT ARRAY[]::integer[]
);

ALTER TABLE public.patient
    ADD COLUMN IF NOT EXISTS family_group_id integer;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname='patient_family_group_id_fkey') THEN
        ALTER TABLE public.patient
            ADD CONSTRAINT patient_family_group_id_fkey
            FOREIGN KEY (family_group_id) REFERENCES public.family_group(record_id) ON DELETE SET NULL;
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS ix_patient_family_group_id ON public.patient(family_group_id);

CREATE OR REPLACE FUNCTION public.validate_family_group_members()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE missing_id integer;
BEGIN
    NEW.family_group_name := NULLIF(BTRIM(NEW.family_group_name), '');
    IF NEW.family_group_name IS NULL THEN
        RAISE EXCEPTION 'Family group name cannot be empty';
    END IF;
    NEW.member_ids := ARRAY(SELECT DISTINCT value FROM unnest(COALESCE(NEW.member_ids, ARRAY[]::integer[])) value ORDER BY value);
    IF NEW.main_patient_id IS NOT NULL AND NOT (NEW.main_patient_id = ANY(NEW.member_ids)) THEN
        NEW.member_ids := array_prepend(NEW.main_patient_id, NEW.member_ids);
    END IF;
    SELECT value INTO missing_id
    FROM unnest(NEW.member_ids) value
    LEFT JOIN public.patient patient ON patient.record_id=value
    WHERE patient.record_id IS NULL LIMIT 1;
    IF missing_id IS NOT NULL THEN
        RAISE EXCEPTION 'Family group member patient % does not exist', missing_id;
    END IF;
    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS trg_family_group_validate_members ON public.family_group;
CREATE TRIGGER trg_family_group_validate_members
BEFORE INSERT OR UPDATE OF family_group_name, main_patient_id, member_ids ON public.family_group
FOR EACH ROW EXECUTE FUNCTION public.validate_family_group_members();

CREATE OR REPLACE FUNCTION public.refresh_family_group_members()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE old_group integer; new_group integer; refreshed_members integer[];
BEGIN
    old_group := CASE WHEN TG_OP='INSERT' THEN NULL ELSE OLD.family_group_id END;
    new_group := CASE WHEN TG_OP='DELETE' THEN NULL ELSE NEW.family_group_id END;
    IF old_group IS NOT NULL THEN
        SELECT COALESCE(array_agg(patient.record_id ORDER BY patient.record_id), ARRAY[]::integer[])
        INTO refreshed_members
        FROM public.patient patient WHERE patient.family_group_id=old_group;
        UPDATE public.family_group group_row
        SET member_ids=refreshed_members,
            main_patient_id=CASE
                WHEN group_row.main_patient_id=ANY(refreshed_members) THEN group_row.main_patient_id
                ELSE refreshed_members[1]
            END
        WHERE group_row.record_id=old_group;
    END IF;
    IF new_group IS NOT NULL AND new_group IS DISTINCT FROM old_group THEN
        UPDATE public.family_group group_row
        SET member_ids=COALESCE((SELECT array_agg(patient.record_id ORDER BY patient.record_id)
                                 FROM public.patient patient WHERE patient.family_group_id=new_group), ARRAY[]::integer[])
        WHERE group_row.record_id=new_group;
    END IF;
    RETURN COALESCE(NEW, OLD);
END $$;

DROP TRIGGER IF EXISTS trg_patient_refresh_family_group ON public.patient;
CREATE TRIGGER trg_patient_refresh_family_group
AFTER INSERT OR UPDATE OF family_group_id OR DELETE ON public.patient
FOR EACH ROW EXECUTE FUNCTION public.refresh_family_group_members();

CREATE TABLE IF NOT EXISTS public.patient_debt_log (
    log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_record_id integer NOT NULL,
    reference_code varchar NOT NULL,
    user_id varchar NOT NULL,
    "timestamp" timestamp with time zone NOT NULL DEFAULT clock_timestamp(),
    debt_change numeric(12,2) NOT NULL CHECK (debt_change > 0),
    debt_direction char(1) NOT NULL CHECK (debt_direction IN ('+', '-'))
);
CREATE INDEX IF NOT EXISTS ix_patient_debt_log_patient_time
    ON public.patient_debt_log(patient_record_id, "timestamp" DESC);
CREATE INDEX IF NOT EXISTS ix_patient_debt_log_reference
    ON public.patient_debt_log(reference_code);

DO $$
DECLARE table_name text;
BEGIN
    FOREACH table_name IN ARRAY ARRAY['users','doctor','pharmacy','faculty','kurum','depot','patient','family_group']
    LOOP
        EXECUTE format($sql$
            CREATE TABLE IF NOT EXISTS public.%I (
                log_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                record_key varchar NOT NULL,
                operation varchar(6) NOT NULL CHECK (operation IN ('INSERT','UPDATE','DELETE')),
                old_data jsonb,
                new_data jsonb,
                user_id varchar NOT NULL,
                "timestamp" timestamp with time zone NOT NULL DEFAULT clock_timestamp()
            )$sql$, table_name || '_log');
        EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON public.%I(record_key, "timestamp" DESC)',
                       'ix_' || table_name || '_log_record_time', table_name || '_log');
    END LOOP;
END $$;

CREATE OR REPLACE FUNCTION public.audit_minor_card_change()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    old_json jsonb := CASE WHEN TG_OP='INSERT' THEN NULL ELSE to_jsonb(OLD) END;
    new_json jsonb := CASE WHEN TG_OP='DELETE' THEN NULL ELSE to_jsonb(NEW) END;
    row_json jsonb := COALESCE(new_json, old_json);
    key_column text := TG_ARGV[1];
    audit_user text;
    audit_time timestamptz := clock_timestamp();
    audit_id bigint;
    old_debt numeric := COALESCE((old_json->>'debt_amount')::numeric, 0);
    new_debt numeric := COALESCE((new_json->>'debt_amount')::numeric, 0);
    debt_delta numeric;
    debt_reference text;
BEGIN
    audit_user := COALESCE(
        NULLIF(current_setting('pharmacy.user_id', true), ''),
        NULLIF(regexp_replace(current_setting('application_name', true), '^pharmacyApp:', ''), current_setting('application_name', true)),
        session_user);

    EXECUTE format('INSERT INTO public.%I(record_key, operation, old_data, new_data, user_id, "timestamp") VALUES ($1,$2,$3,$4,$5,$6) RETURNING log_id', TG_ARGV[0])
    INTO audit_id USING row_json->>key_column, TG_OP, old_json, new_json, audit_user, audit_time;

    IF TG_TABLE_NAME='patient' THEN
        debt_delta := new_debt-old_debt;
        IF debt_delta <> 0 THEN
            debt_reference := COALESCE(NULLIF(current_setting('pharmacy.reference_code', true), ''), 'H' || audit_id::text);
            INSERT INTO public.patient_debt_log(
                patient_record_id, reference_code, user_id, "timestamp", debt_change, debt_direction)
            VALUES ((row_json->>'record_id')::integer, debt_reference, audit_user, audit_time,
                    ABS(debt_delta), CASE WHEN debt_delta > 0 THEN '+' ELSE '-' END);
        END IF;
    END IF;
    RETURN COALESCE(NEW, OLD);
END $$;

DO $$
DECLARE item record;
BEGIN
    FOR item IN SELECT * FROM (VALUES
        ('users','user_id'), ('doctor','record_id'), ('pharmacy','record_id'),
        ('faculty','record_id'), ('kurum','record_id'), ('depot','record_id'),
        ('patient','record_id'), ('family_group','record_id')) values_list(table_name,key_column)
    LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.%I', 'trg_' || item.table_name || '_audit', item.table_name);
        EXECUTE format('CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.audit_minor_card_change(%L,%L)',
                       'trg_' || item.table_name || '_audit', item.table_name, item.table_name || '_log', item.key_column);
    END LOOP;
END $$;

