    ON public."qrInactive" (barcode);

CREATE OR REPLACE FUNCTION public.pharmacy_qr_gtin14(value varchar)
RETURNS varchar
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
DECLARE
    cleaned varchar := regexp_replace(value, E'^\\]d2', '');
    parsed varchar;
BEGIN
    parsed := substring(cleaned FROM E'\\(01\\)([0-9]{14})');
    IF parsed IS NULL AND cleaned ~ '^01[0-9]{14}' THEN
        parsed := substring(cleaned FROM 3 FOR 14);
    END IF;
    RETURN parsed;
END;
$$;

CREATE OR REPLACE FUNCTION public.pharmacy_qr_barcode(value varchar)
RETURNS varchar
LANGUAGE plpgsql
STABLE
STRICT
AS $$
DECLARE
    gtin varchar := public.pharmacy_qr_gtin14(value);
    gtin13 varchar;
    catalog_barcode varchar;
BEGIN
    IF gtin IS NULL THEN
        RETURN NULL;
    END IF;

    gtin13 := CASE WHEN left(gtin, 1) = '0' THEN substring(gtin FROM 2) ELSE gtin END;
    SELECT b.barcode
    INTO catalog_barcode
    FROM public.barcode b
    WHERE b.barcode IN (gtin, gtin13)
    ORDER BY CASE WHEN b.barcode = gtin13 THEN 0 ELSE 1 END
    LIMIT 1;

    RETURN COALESCE(catalog_barcode, gtin13);
END;
$$;

CREATE OR REPLACE FUNCTION public.pharmacy_qr_expiry(value varchar)
RETURNS date
LANGUAGE plpgsql
IMMUTABLE
STRICT
AS $$
DECLARE
    cleaned varchar := regexp_replace(value, E'^\\]d2', '');
    encoded varchar;
    parsed_year integer;
    parsed_month integer;
    parsed_day integer;
BEGIN
    encoded := substring(cleaned FROM E'\\(17\\)([0-9]{6})');
    IF encoded IS NULL AND cleaned ~ '^01[0-9]{14}' THEN
        encoded := substring(substring(cleaned FROM 17) FROM '17([0-9]{6})');
    END IF;
    IF encoded IS NULL THEN
        RETURN NULL;
    END IF;

    parsed_year := 2000 + substring(encoded FROM 1 FOR 2)::integer;
    parsed_month := substring(encoded FROM 3 FOR 2)::integer;
    parsed_day := substring(encoded FROM 5 FOR 2)::integer;
    IF parsed_month NOT BETWEEN 1 AND 12 THEN
        RETURN NULL;
    END IF;
    IF parsed_day = 0 THEN
        RETURN (make_date(parsed_year, parsed_month, 1) + interval '1 month - 1 day')::date;
    END IF;
    RETURN make_date(parsed_year, parsed_month, parsed_day);
EXCEPTION WHEN datetime_field_overflow THEN
    RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.pharmacy_refresh_barcode_active(target_barcode varchar)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
    UPDATE public."barcodeActive" aggregate_stock
    SET quantity = current_stock.quantity,
        nearest_expiry_date = current_stock.nearest_expiry_date
    FROM (
        SELECT count(*)::integer AS quantity, min(expiry_date) AS nearest_expiry_date
        FROM public."qrActive"
        WHERE barcode = target_barcode
    ) current_stock
    WHERE aggregate_stock.barcode = target_barcode;
END;
$$;

CREATE OR REPLACE FUNCTION public.pharmacy_apply_qr_movement()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    active_row public."qrActive"%ROWTYPE;
    inactive_row public."qrInactive"%ROWTYPE;
    parsed_barcode varchar;
    parsed_expiry date;
    inserted_count integer;
BEGIN
    IF NEW.movement_type IN (
        'DEP_IN', 'FIRM_IN', 'TRANSF_IN', 'PERAK_RETURN',
        'PRESC_RETURN', 'MAN_IN', 'QR_ADD'
    ) THEN
        SELECT * INTO inactive_row
        FROM public."qrInactive"
        WHERE qr_code = NEW.qr_code
        FOR UPDATE;

        parsed_barcode := COALESCE(inactive_row.barcode, public.pharmacy_qr_barcode(NEW.qr_code));
        parsed_expiry := COALESCE(inactive_row.expiry_date, public.pharmacy_qr_expiry(NEW.qr_code));
        IF parsed_barcode IS NULL THEN
            RAISE EXCEPTION 'Karekoddan barkod bilgisi okunamadı.'
                USING ERRCODE = '22023';
        END IF;

        INSERT INTO public."qrActive" (
            qr_code, barcode, expiry_date, status, purchase_cost, reference_no
        ) VALUES (
            NEW.qr_code, parsed_barcode, parsed_expiry, 'ACTIVE',
            inactive_row.entry_cost, NEW.reference_code
        )
        ON CONFLICT (qr_code) DO NOTHING;
        GET DIAGNOSTICS inserted_count = ROW_COUNT;

        IF inserted_count = 0 THEN
            RAISE EXCEPTION 'Karekod zaten aktif stokta: %', NEW.qr_code
                USING ERRCODE = '23505';
        END IF;

        DELETE FROM public."qrInactive" WHERE qr_code = NEW.qr_code;
        PERFORM public.pharmacy_refresh_barcode_active(parsed_barcode);
        RETURN NEW;
    END IF;

    IF NEW.movement_type IN (
        'DEP_RETURN', 'FIRM_RETURN', 'TRANSF_OUT', 'PERAK_OUT',
        'PRESC_OUT', 'DESTRUCTION', 'MAN_OUT'
    ) THEN
        SELECT * INTO active_row
        FROM public."qrActive"
        WHERE qr_code = NEW.qr_code
        FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Karekod aktif stokta bulunamadı: %', NEW.qr_code
                USING ERRCODE = 'P0002';
        END IF;

        INSERT INTO public."qrInactive" (
            qr_code, barcode, expiry_date, entry_cost, exit_price, reference_no
        ) VALUES (
            active_row.qr_code, active_row.barcode, active_row.expiry_date,
            active_row.purchase_cost, NULL, NEW.reference_code
        )
        ON CONFLICT (qr_code) DO UPDATE
        SET barcode = EXCLUDED.barcode,
            expiry_date = EXCLUDED.expiry_date,
            entry_cost = EXCLUDED.entry_cost,
            exit_price = EXCLUDED.exit_price,
            reference_no = EXCLUDED.reference_no;

        DELETE FROM public."qrActive" WHERE qr_code = NEW.qr_code;
        PERFORM public.pharmacy_refresh_barcode_active(active_row.barcode);
        RETURN NEW;
    END IF;

    SELECT * INTO active_row
    FROM public."qrActive"
    WHERE qr_code = NEW.qr_code
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Karekod aktif stokta bulunamadı: %', NEW.qr_code
            USING ERRCODE = 'P0002';
    END IF;

    UPDATE public."qrActive"
    SET status = CASE NEW.movement_type
        WHEN 'QUAR_IN' THEN 'QUARANTINE'
        WHEN 'QUAR_OUT' THEN 'ACTIVE'
        WHEN 'RECALL' THEN 'RECALLED'
        WHEN 'RESERVED' THEN 'RESERVED'
        WHEN 'DAMAGED' THEN 'DAMAGED'
        ELSE status
    END,
    reference_no = COALESCE(NEW.reference_code, reference_no)
    WHERE qr_code = NEW.qr_code;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_qrMovements_apply_stock ON public."qrMovements";
CREATE TRIGGER trg_qrMovements_apply_stock
AFTER INSERT ON public."qrMovements"
FOR EACH ROW
EXECUTE FUNCTION public.pharmacy_apply_qr_movement();

COMMIT;
