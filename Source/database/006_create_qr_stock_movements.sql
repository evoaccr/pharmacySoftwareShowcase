CREATE UNIQUE INDEX IF NOT EXISTS ux_barcode_barcode
    ON public.barcode (barcode);

CREATE TABLE IF NOT EXISTS public."barcodeActive" (
    barcode varchar PRIMARY KEY REFERENCES public.barcode (barcode),
    quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    nearest_expiry_date date,
    status varchar,
    order_quantity integer NOT NULL DEFAULT 0 CHECK (order_quantity >= 0),
    consignment_quantity integer NOT NULL DEFAULT 0 CHECK (consignment_quantity >= 0),
    pending_quantity integer NOT NULL DEFAULT 0 CHECK (pending_quantity >= 0),
    order_reference_codes varchar[] NOT NULL DEFAULT ARRAY[]::varchar[]
);

INSERT INTO public."barcodeActive" (barcode, quantity, status)
SELECT barcode, 0, 'ACTIVE'
FROM public.barcode
WHERE NULLIF(btrim(barcode), '') IS NOT NULL
ON CONFLICT (barcode) DO NOTHING;

CREATE TABLE IF NOT EXISTS public."qrActive" (
    qr_code varchar PRIMARY KEY,
    barcode varchar NOT NULL,
    expiry_date date,
    status varchar NOT NULL DEFAULT 'ACTIVE',
    purchase_cost numeric(12,2),
    reference_no varchar
);

CREATE TABLE IF NOT EXISTS public."qrInactive" (
    qr_code varchar PRIMARY KEY,
    barcode varchar NOT NULL,
    expiry_date date,
    entry_cost numeric(12,2),
    exit_price numeric(12,2),
    reference_no varchar
);

CREATE TABLE IF NOT EXISTS public."qrMovements" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qr_code varchar NOT NULL,
    movement_type varchar NOT NULL,
    movement_date timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    movement_address varchar,
    user_id varchar,
    reference_code varchar,
    CONSTRAINT ck_qrMovements_movement_type CHECK (movement_type IN (
        'DEP_IN', 'DEP_RETURN', 'FIRM_IN', 'FIRM_RETURN',
        'TRANSF_IN', 'TRANSF_OUT', 'PERAK_OUT', 'PERAK_RETURN',
        'PRESC_OUT', 'PRESC_RETURN', 'QUAR_IN', 'QUAR_OUT',
        'DESTRUCTION', 'RECALL', 'MAN_IN', 'MAN_OUT', 'QR_ADD',
        'RESERVED', 'DAMAGED'
    ))
);

CREATE INDEX IF NOT EXISTS idx_qrMovements_movement_date
    ON public."qrMovements" (movement_date DESC);
CREATE INDEX IF NOT EXISTS idx_qrMovements_qr_code_date
    ON public."qrMovements" (qr_code, movement_date DESC);
CREATE INDEX IF NOT EXISTS idx_qrMovements_type_date
    ON public."qrMovements" (movement_type, movement_date DESC);
