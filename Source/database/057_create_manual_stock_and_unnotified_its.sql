CREATE TABLE IF NOT EXISTS public.manual_movements (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_direction varchar NOT NULL,
    its_notification_enabled boolean NOT NULL DEFAULT TRUE,
    its_notification_id varchar,
    user_id varchar NOT NULL REFERENCES public.users(user_id),
    note varchar,
    "timestamp" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_manual_movements_direction
        CHECK (movement_direction IN ('IN', 'OUT'))
);

CREATE TABLE IF NOT EXISTS public.unnotified_its_movements (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    qr_code varchar NOT NULL,
    reference_no varchar NOT NULL,
    movement_direction varchar NOT NULL,
    notification_type varchar NOT NULL,
    is_corrected boolean NOT NULL DEFAULT FALSE,
    created_by varchar NOT NULL REFERENCES public.users(user_id),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    corrected_by varchar REFERENCES public.users(user_id),
    corrected_at timestamp without time zone,
    correction_notification_id varchar,
    paired_record_id integer REFERENCES public.unnotified_its_movements(record_id),
    CONSTRAINT ck_unnotified_its_direction
        CHECK (movement_direction IN ('IN', 'OUT')),
    CONSTRAINT ck_unnotified_its_notification_type
        CHECK (notification_type IN ('SALE', 'SALE_CANCELLATION', 'ACCEPTANCE')),
    CONSTRAINT ck_unnotified_its_correction_state
        CHECK ((NOT is_corrected AND corrected_at IS NULL) OR is_corrected)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_unnotified_its_open_qr
    ON public.unnotified_its_movements(qr_code)
    WHERE NOT is_corrected;
CREATE INDEX IF NOT EXISTS ix_unnotified_its_reference
    ON public.unnotified_its_movements(reference_no);
CREATE INDEX IF NOT EXISTS ix_unnotified_its_created
    ON public.unnotified_its_movements(created_at DESC);

CREATE TABLE IF NOT EXISTS public.stock_its_operations (
    operation_id uuid PRIMARY KEY,
    operation_type varchar NOT NULL,
    operation_status varchar NOT NULL,
    pharmacy_gln varchar NOT NULL,
    request_payload jsonb NOT NULL,
    qr_codes varchar[] NOT NULL DEFAULT ARRAY[]::varchar[],
    requested_by varchar NOT NULL REFERENCES public.users(user_id),
    source_reference varchar,
    prepared_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    remote_confirmed_at timestamp with time zone,
    local_completed_at timestamp with time zone,
    notification_id varchar,
    http_status integer,
    response_body text,
    fault_code varchar,
    fault_message text,
    error_text text,
    manual_movement_id integer REFERENCES public.manual_movements(record_id),
    CONSTRAINT ck_stock_its_operation_type
        CHECK (operation_type IN ('SALE', 'SALE_CANCELLATION', 'ACCEPTANCE')),
    CONSTRAINT ck_stock_its_operation_status
        CHECK (operation_status IN (
            'prepared', 'remote_confirmed', 'local_completed',
            'definitely_not_sent', 'failed', 'reconciliation_required'))
);

CREATE TABLE IF NOT EXISTS public.stock_its_operation_items (
    operation_id uuid NOT NULL
        REFERENCES public.stock_its_operations(operation_id) ON DELETE CASCADE,
    qr_code varchar NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    result_code varchar,
    error_text text,
    PRIMARY KEY (operation_id, qr_code)
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_stock_its_operation_items_active_qr
    ON public.stock_its_operation_items(qr_code)
    WHERE is_active;
CREATE INDEX IF NOT EXISTS ix_stock_its_operations_status_time
    ON public.stock_its_operations(operation_status, prepared_at DESC);

COMMIT;
