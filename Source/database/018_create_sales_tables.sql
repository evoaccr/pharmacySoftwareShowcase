BEGIN;

CREATE TABLE IF NOT EXISTS public."payementTypes" (
    record_id smallint PRIMARY KEY,
    payment_type varchar NOT NULL UNIQUE
);

INSERT INTO public."payementTypes" (record_id, payment_type) VALUES
    (1, 'cash'),
    (2, 'credit'),
    (3, 'banktransfer'),
    (4, 'debt'),
    (5, 'institution')
ON CONFLICT (record_id) DO UPDATE
SET payment_type = EXCLUDED.payment_type;

CREATE TABLE IF NOT EXISTS public.sales (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer REFERENCES public.patient (record_id),
    its_no varchar,
    institution_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (institution_amount >= 0),
    total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0),
    payement_finished boolean NOT NULL DEFAULT FALSE,
    institution_payement_finished boolean NOT NULL DEFAULT FALSE,
    debted boolean NOT NULL DEFAULT FALSE,
    prescription_no varchar,
    user_no varchar REFERENCES public.users (user_id),
    "timestamp" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    invoice_no varchar,
    CONSTRAINT ck_sales_institution_amount CHECK (institution_amount <= total_amount)
);

CREATE TABLE IF NOT EXISTS public."salesPayements" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id integer NOT NULL REFERENCES public.sales (record_id) ON DELETE CASCADE,
    payment_type smallint NOT NULL REFERENCES public."payementTypes" (record_id),
    amount numeric(12,2) NOT NULL CHECK (amount > 0)
);

CREATE INDEX IF NOT EXISTS ix_sales_patient_timestamp
    ON public.sales (patient_id, "timestamp" DESC);
CREATE INDEX IF NOT EXISTS ix_sales_prescription_no
    ON public.sales (prescription_no)
    WHERE prescription_no IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_salesPayements_sale_id
    ON public."salesPayements" (sale_id);

CREATE OR REPLACE FUNCTION public.pharmacy_refresh_sale_payment_status(target_sale_id integer)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    sale_total numeric(12,2);
    institution_due numeric(12,2);
    customer_paid numeric(12,2);
    institution_paid numeric(12,2);
    all_paid numeric(12,2);
BEGIN
    SELECT total_amount, institution_amount
    INTO sale_total, institution_due
    FROM public.sales
    WHERE record_id = target_sale_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    SELECT
        COALESCE(SUM(payment.amount) FILTER (WHERE type.payment_type <> 'institution'), 0),
        COALESCE(SUM(payment.amount) FILTER (WHERE type.payment_type = 'institution'), 0),
        COALESCE(SUM(payment.amount), 0)
    INTO customer_paid, institution_paid, all_paid
    FROM public."salesPayements" payment
    JOIN public."payementTypes" type ON type.record_id = payment.payment_type
    WHERE payment.sale_id = target_sale_id;

    UPDATE public.sales
    SET payement_finished = customer_paid >= (sale_total - institution_due),
        institution_payement_finished = institution_paid >= institution_due
            AND all_paid >= sale_total
    WHERE record_id = target_sale_id;
END;
$$;

CREATE OR REPLACE FUNCTION public.pharmacy_apply_sale_payment_status()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.sale_id IS DISTINCT FROM NEW.sale_id THEN
        PERFORM public.pharmacy_refresh_sale_payment_status(OLD.sale_id);
    END IF;
    PERFORM public.pharmacy_refresh_sale_payment_status(
        CASE WHEN TG_OP = 'DELETE' THEN OLD.sale_id ELSE NEW.sale_id END);
    RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS trg_salesPayements_refresh_sale ON public."salesPayements";
CREATE TRIGGER trg_salesPayements_refresh_sale
AFTER INSERT OR UPDATE OR DELETE ON public."salesPayements"
FOR EACH ROW
EXECUTE FUNCTION public.pharmacy_apply_sale_payment_status();

COMMIT;
