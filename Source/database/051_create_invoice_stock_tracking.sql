BEGIN;
SET LOCAL lock_timeout = '5s';

ALTER TABLE public.invoice_lines
    ADD COLUMN IF NOT EXISTS stock_tracking_type text NOT NULL DEFAULT 'NONE',
    ADD COLUMN IF NOT EXISTS tracking_warning text NOT NULL DEFAULT '';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.invoice_lines'::regclass
          AND conname = 'invoice_lines_stock_tracking_type_check') THEN
        ALTER TABLE public.invoice_lines
            ADD CONSTRAINT invoice_lines_stock_tracking_type_check
            CHECK (stock_tracking_type IN ('NONE', 'BARCODE', 'QR'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.invoice_line_qr_codes (
    record_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_line_id integer NOT NULL
        REFERENCES public.invoice_lines(record_id) ON DELETE CASCADE,
    qr_code text NOT NULL,
    gtin text NOT NULL,
    barcode text NOT NULL,
    serial_number text NOT NULL,
    batch_number text NOT NULL,
    expiry_date date NOT NULL,
    raw_code text NOT NULL DEFAULT '',
    CONSTRAINT invoice_line_qr_codes_line_code_unique UNIQUE (invoice_line_id, qr_code)
);

CREATE INDEX IF NOT EXISTS invoice_line_qr_codes_line_idx
    ON public.invoice_line_qr_codes(invoice_line_id);
CREATE INDEX IF NOT EXISTS invoice_line_qr_codes_gtin_serial_idx
    ON public.invoice_line_qr_codes(gtin, serial_number);

CREATE TABLE IF NOT EXISTS public.invoice_stock_logs (
    record_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_uuid text NOT NULL REFERENCES public.invoices(invoice_uuid),
    action_code text NOT NULL,
    occurred_at timestamp with time zone NOT NULL DEFAULT now(),
    user_id varchar NOT NULL REFERENCES public.users(user_id),
    reference_code varchar NOT NULL UNIQUE,
    movement_type_code varchar NOT NULL,
    related_log_id bigint REFERENCES public.invoice_stock_logs(record_id),
    counterparty_address_id integer REFERENCES public.addresses(record_id),
    stock_line_count integer NOT NULL DEFAULT 0 CHECK (stock_line_count >= 0),
    serialized_quantity integer NOT NULL DEFAULT 0 CHECK (serialized_quantity >= 0),
    barcode_quantity integer NOT NULL DEFAULT 0 CHECK (barcode_quantity >= 0),
    movement_count integer NOT NULL DEFAULT 0 CHECK (movement_count >= 0),
    notes text NOT NULL DEFAULT '',
    metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT invoice_stock_logs_action_check CHECK (
        action_code IN ('SAVE', 'REFUND', 'PARTIAL_REFUND'))
);

CREATE INDEX IF NOT EXISTS invoice_stock_logs_invoice_time_idx
    ON public.invoice_stock_logs(invoice_uuid, occurred_at DESC, record_id DESC);
CREATE INDEX IF NOT EXISTS invoice_stock_logs_user_time_idx
    ON public.invoice_stock_logs(user_id, occurred_at DESC);

DROP TRIGGER IF EXISTS trg_qrMovements_apply_invoice_unsave ON public."qrMovements";
DROP FUNCTION IF EXISTS public.pharmacy_apply_invoice_unsave_movement();

COMMIT;
