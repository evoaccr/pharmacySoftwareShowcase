CREATE TABLE IF NOT EXISTS public."consignmentSales" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id integer NOT NULL REFERENCES public.patient (record_id),
    total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0),
    paid_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    debt_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (debt_amount >= 0),
    discount_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    refunded_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (refunded_amount >= 0),
    debt_reversed_amount numeric(12,2) NOT NULL DEFAULT 0 CHECK (debt_reversed_amount >= 0),
    with_iskonto boolean NOT NULL DEFAULT FALSE,
    status varchar NOT NULL DEFAULT 'reserved',
    settlement_sale_id integer REFERENCES public.sales (record_id),
    user_no varchar REFERENCES public.users (user_id),
    settled_by varchar REFERENCES public.users (user_id),
    "timestamp" timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    settled_at timestamp without time zone,
    marked boolean NOT NULL DEFAULT FALSE,
    notes varchar,
    CONSTRAINT ck_consignment_sales_accounting
        CHECK (paid_amount + debt_amount + discount_amount = total_amount),
    CONSTRAINT ck_consignment_sales_status
        CHECK (status IN ('reserved', 'converted_to_retail', 'returned', 'converted_to_prescription'))
);

CREATE TABLE IF NOT EXISTS public."consignmentSaleItems" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consignment_sale_id integer NOT NULL
        REFERENCES public."consignmentSales" (record_id) ON DELETE CASCADE,
    qr_code varchar NOT NULL,
    barcode varchar NOT NULL,
    gross_price numeric(12,2) NOT NULL CHECK (gross_price >= 0),
    discount_amount numeric(12,2) NOT NULL DEFAULT 0
        CHECK (discount_amount >= 0 AND discount_amount <= gross_price),
    net_price numeric(12,2) NOT NULL CHECK (net_price >= 0),
    entry_cost numeric(12,2),
    CONSTRAINT ck_consignment_sale_items_net_price
        CHECK (net_price = gross_price - discount_amount)
);

