BEGIN;

LOCK TABLE public.barcode IN ACCESS EXCLUSIVE MODE;
LOCK TABLE public."barcodePrices" IN ACCESS EXCLUSIVE MODE;

ALTER TABLE public.barcode
    ADD COLUMN IF NOT EXISTS kamu_no varchar,
    ADD COLUMN IF NOT EXISTS strength varchar,
    ADD COLUMN IF NOT EXISTS product_prefix varchar;

-- Preserve the required unique values before removing the source JSON.
DO $$
DECLARE
    mismatch_count bigint;
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'barcode'
          AND column_name = 'source_product'
    ) THEN
        EXECUTE $migrate_product$
            UPDATE public.barcode
            SET kamu_no = COALESCE(kamu_no, NULLIF(source_product ->> 'kamu_no', ''))
        $migrate_product$;
        EXECUTE $verify_product$
            SELECT count(*)
            FROM public.barcode
            WHERE NULLIF(source_product ->> 'kamu_no', '') IS NOT NULL
              AND kamu_no IS DISTINCT FROM NULLIF(source_product ->> 'kamu_no', '')
        $verify_product$ INTO mismatch_count;
        IF mismatch_count <> 0 THEN
            RAISE EXCEPTION 'kamu_no migration verification failed for % row(s)', mismatch_count;
        END IF;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'barcode'
          AND column_name = 'source_package'
    ) THEN
        EXECUTE $migrate_package$
            UPDATE public.barcode
            SET strength = COALESCE(strength, NULLIF(source_package ->> 'etkinlik', '')),
                product_prefix = COALESCE(product_prefix, NULLIF(source_package ->> 'urun_onek', ''))
        $migrate_package$;
        EXECUTE $verify_package$
            SELECT count(*)
            FROM public.barcode
            WHERE (NULLIF(source_package ->> 'etkinlik', '') IS NOT NULL
                   AND strength IS DISTINCT FROM NULLIF(source_package ->> 'etkinlik', ''))
               OR (NULLIF(source_package ->> 'urun_onek', '') IS NOT NULL
                   AND product_prefix IS DISTINCT FROM NULLIF(source_package ->> 'urun_onek', ''))
        $verify_package$ INTO mismatch_count;
        IF mismatch_count <> 0 THEN
            RAISE EXCEPTION 'source_package migration verification failed for % row(s)', mismatch_count;
        END IF;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public."barcodePriceHistory" (
    history_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_reference_no bigint NOT NULL REFERENCES public.barcode (record_id),
    effective_date date NOT NULL,
    sale_price numeric(12,2),
    public_price numeric(12,2),
    public_paid_price numeric(12,2),
    price_difference numeric(12,2),
    vat_rate numeric(5,2),
    discount_rate numeric(5,2),
    warehouse_price numeric(12,2),
    manufacturer_price numeric(12,2)
);

CREATE INDEX IF NOT EXISTS idx_barcodePriceHistory_reference_date
    ON public."barcodePriceHistory" (record_reference_no, effective_date DESC);

DO $$
DECLARE
    invalid_count bigint;
    expected_count bigint;
    inserted_count bigint;
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'barcodePrices'
          AND column_name = 'price_history'
    ) THEN
        EXECUTE $history_invalid$
            SELECT count(*)
            FROM public."barcodePrices"
            WHERE price_history IS NOT NULL
              AND jsonb_typeof(price_history) <> 'array'
        $history_invalid$ INTO invalid_count;
        IF invalid_count <> 0 THEN
            RAISE EXCEPTION 'price_history is not an array for % product(s)', invalid_count;
        END IF;

        EXECUTE $history_entry_invalid$
            WITH entries AS (
                SELECT item
                FROM public."barcodePrices" bp
                CROSS JOIN LATERAL jsonb_array_elements(bp.price_history) AS entries(item)
                WHERE jsonb_typeof(bp.price_history) = 'array'
            )
            SELECT count(*)
            FROM entries
            WHERE jsonb_typeof(item) <> 'array'
               OR jsonb_array_length(item) < 2
               OR jsonb_typeof(item -> 1) <> 'array'
               OR jsonb_array_length(item -> 1) < 6
               OR NOT (
                    ((item ->> 0) ~ '^[0-9]{2}/[0-9]{2}/[0-9]{4}$'
                     AND to_char(to_date(item ->> 0, 'DD/MM/YYYY'), 'DD/MM/YYYY') = item ->> 0)
                    OR
                    ((item ->> 0) ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
                     AND to_char(to_date(item ->> 0, 'YYYY-MM-DD'), 'YYYY-MM-DD') = item ->> 0)
               )
        $history_entry_invalid$ INTO invalid_count;
        IF invalid_count <> 0 THEN
            RAISE EXCEPTION 'price_history contains % malformed/unmappable entries', invalid_count;
        END IF;

        EXECUTE $history_count$
            SELECT COALESCE(sum(jsonb_array_length(price_history)), 0)
            FROM public."barcodePrices"
            WHERE jsonb_typeof(price_history) = 'array'
        $history_count$ INTO expected_count;

        EXECUTE $history_insert$
            INSERT INTO public."barcodePriceHistory" (
                record_reference_no, effective_date, sale_price, public_price,
                public_paid_price, price_difference, vat_rate, discount_rate,
                warehouse_price, manufacturer_price
            )
            SELECT
                bp.record_reference_no,
                CASE
                    WHEN item ->> 0 ~ '^[0-9]{2}/[0-9]{2}/[0-9]{4}$'
                        THEN to_date(item ->> 0, 'DD/MM/YYYY')
                    ELSE to_date(item ->> 0, 'YYYY-MM-DD')
                END,
                NULLIF(item -> 1 ->> 0, '')::numeric(12,2),
                NULL,
                NULLIF(item -> 1 ->> 1, '')::numeric(12,2),
                NULL,
                NULLIF(item -> 1 ->> 2, '')::numeric(5,2),
                NULLIF(item -> 1 ->> 3, '')::numeric(5,2),
                NULLIF(item -> 1 ->> 4, '')::numeric(12,2),
                NULLIF(item -> 1 ->> 5, '')::numeric(12,2)
            FROM public."barcodePrices" bp
            CROSS JOIN LATERAL jsonb_array_elements(bp.price_history) AS entries(item)
            WHERE jsonb_typeof(bp.price_history) = 'array'
        $history_insert$;
        GET DIAGNOSTICS inserted_count = ROW_COUNT;
        IF inserted_count <> expected_count THEN
            RAISE EXCEPTION 'price history migration count mismatch: expected %, inserted %', expected_count, inserted_count;
        END IF;
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS public."barcodeCampaign" (
    campaign_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_reference_no bigint NOT NULL REFERENCES public.barcode (record_id),
    warehouse_gln varchar NOT NULL,
    purchase_quantity integer NOT NULL,
    bonus_quantity integer NOT NULL,
    period_days integer,
    start_date date,
    end_date date,
    CONSTRAINT barcode_campaign_purchase_quantity_check CHECK (purchase_quantity > 0),
    CONSTRAINT barcode_campaign_bonus_quantity_check CHECK (bonus_quantity >= 0),
    CONSTRAINT barcode_campaign_period_days_check CHECK (period_days IS NULL OR period_days > 0),
    CONSTRAINT barcode_campaign_dates_check CHECK (
        start_date IS NULL OR end_date IS NULL OR end_date >= start_date
    )
);

CREATE INDEX IF NOT EXISTS idx_barcodeCampaign_reference_dates
    ON public."barcodeCampaign" (record_reference_no, start_date, end_date);
CREATE INDEX IF NOT EXISTS idx_barcodeCampaign_warehouse_gln
    ON public."barcodeCampaign" (warehouse_gln);

DO $$
DECLARE
    invalid_count bigint;
    missing_current_count bigint;
    expected_count bigint;
    inserted_count bigint;
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name = 'barcodePrices'
          AND column_name = 'campaign_periods'
    ) THEN
        EXECUTE $campaign_invalid_type$
            SELECT count(*)
            FROM public."barcodePrices"
            WHERE campaign_periods IS NOT NULL
              AND jsonb_typeof(campaign_periods) <> 'array'
        $campaign_invalid_type$ INTO invalid_count;
        IF invalid_count <> 0 THEN
            RAISE EXCEPTION 'campaign_periods is not an array for % product(s)', invalid_count;
        END IF;

        EXECUTE $campaign_invalid_entry$
            WITH entries AS (
                SELECT item
                FROM public."barcodePrices" bp
                CROSS JOIN LATERAL jsonb_array_elements(bp.campaign_periods) AS entries(item)
                WHERE jsonb_typeof(bp.campaign_periods) = 'array'
            )
            SELECT count(*)
            FROM entries
            WHERE jsonb_typeof(item) <> 'array'
               OR jsonb_array_length(item) < 3
               OR NULLIF(item ->> 0, '') IS NULL
               OR replace(item ->> 1, ' ', '') !~ '^[0-9]+\+[0-9]+$'
               OR (item ->> 2) !~ '^[0-9]+$'
               OR (item ->> 2)::integer <= 0
        $campaign_invalid_entry$ INTO invalid_count;
        IF invalid_count <> 0 THEN
            RAISE EXCEPTION 'campaign_periods contains % malformed/unmappable entries', invalid_count;
        END IF;

        IF EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'barcodePrices'
              AND column_name = 'current_campaigns'
        ) THEN
            EXECUTE $campaign_missing_warehouse$
                SELECT count(*)
                FROM public."barcodePrices" bp
                CROSS JOIN LATERAL unnest(bp.current_campaigns) campaign
                WHERE NOT EXISTS (
                    SELECT 1
                    FROM jsonb_array_elements(COALESCE(bp.campaign_periods, '[]'::jsonb)) item
                    WHERE replace(item ->> 1, ' ', '') = replace(campaign, ' ', '')
                )
            $campaign_missing_warehouse$ INTO missing_current_count;
            IF missing_current_count <> 0 THEN
                RAISE EXCEPTION '% current campaign(s) have no warehouse GLN; refusing data loss', missing_current_count;
            END IF;
        END IF;

        EXECUTE $campaign_count$
            SELECT COALESCE(sum(jsonb_array_length(campaign_periods)), 0)
            FROM public."barcodePrices"
            WHERE jsonb_typeof(campaign_periods) = 'array'
        $campaign_count$ INTO expected_count;

        EXECUTE $campaign_insert$
            INSERT INTO public."barcodeCampaign" (
                record_reference_no, warehouse_gln, purchase_quantity,
                bonus_quantity, period_days, start_date, end_date
            )
            SELECT
                bp.record_reference_no,
                item ->> 0,
                split_part(replace(item ->> 1, ' ', ''), '+', 1)::integer,
                split_part(replace(item ->> 1, ' ', ''), '+', 2)::integer,
                (item ->> 2)::integer,
                NULL,
                NULL
            FROM public."barcodePrices" bp
            CROSS JOIN LATERAL jsonb_array_elements(bp.campaign_periods) AS entries(item)
            WHERE jsonb_typeof(bp.campaign_periods) = 'array'
        $campaign_insert$;
        GET DIAGNOSTICS inserted_count = ROW_COUNT;
        IF inserted_count <> expected_count THEN
            RAISE EXCEPTION 'campaign migration count mismatch: expected %, inserted %', expected_count, inserted_count;
        END IF;
    END IF;
END $$;

