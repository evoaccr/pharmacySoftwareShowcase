BEGIN;

CREATE TABLE IF NOT EXISTS public."barcodeAnalysis" (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_reference_no integer REFERENCES public.barcode (record_id) ON DELETE CASCADE,
    wanted_stock_months numeric(4,1) NOT NULL DEFAULT 1.5,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_barcode_analysis_wanted_stock_months
        CHECK (
            wanted_stock_months >= 0.5
            AND wanted_stock_months <= 60.0
            AND wanted_stock_months * 2 = trunc(wanted_stock_months * 2)
        )
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_barcode_analysis_product
    ON public."barcodeAnalysis" (record_reference_no)
    WHERE record_reference_no IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS ux_barcode_analysis_default
    ON public."barcodeAnalysis" ((1))
    WHERE record_reference_no IS NULL;

INSERT INTO public."barcodeAnalysis" (record_reference_no, wanted_stock_months)
SELECT NULL, 1.5
WHERE NOT EXISTS (
    SELECT 1
    FROM public."barcodeAnalysis"
    WHERE record_reference_no IS NULL
);

COMMIT;
