BEGIN;

CREATE TABLE IF NOT EXISTS public.barcode (
    record_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    drug_name varchar,
    photo bytea,
    barcode varchar,
    product_group varchar,
    package_quantity integer,
    company varchar,
    origin varchar,
    equivalent_group varchar,
    alternative_group varchar,
    active_ingredient varchar,
    atc_code varchar,
    sgk_code varchar,
    indication text,
    label text,
    warning text,
    prospectus text,
    dosage text,
    status varchar,
    sut text
);

CREATE TABLE IF NOT EXISTS public."barcodePrices" (
    record_reference_no integer PRIMARY KEY
        REFERENCES public.barcode (record_id),
    purchase_price decimal,
    sale_price decimal,
    public_price decimal,
    vat_rate decimal,
    discount_rate decimal,
    warehouse_price decimal,
    manufacturer_price decimal,
    current_campaign varchar[],
    best_campaign varchar[],
    campaign_period varchar[][],
    price_history varchar[][]
);

COMMIT;
