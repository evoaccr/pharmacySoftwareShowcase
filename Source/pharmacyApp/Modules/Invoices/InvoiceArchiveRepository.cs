    public async Task<int> MarkMissingDeletedAsync(
        string portalTypeKey,
        DateOnly rangeStart,
        DateOnly rangeEnd,
        IReadOnlyCollection<string> seenLogicalKeys,
        CancellationToken cancellationToken = default)
    {
        await using var connection = DatabaseConnectionSettingsStore.CreateConnection();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        var seen = seenLogicalKeys.ToHashSet(StringComparer.Ordinal);
        const string selectSql = """
            SELECT DISTINCT ON (logical_key) record_id, logical_key, version_no
            FROM public.invoices
            WHERE portal_type_key = @type_key AND issue_date BETWEEN @range_start AND @range_end
            ORDER BY logical_key, version_no DESC;
            """;
        var missing = new List<(int RecordId, string LogicalKey, int VersionNo)>();
        await using (var select = pharmacyApp.Infrastructure.DatabaseCommand.Create(selectSql, connection, transaction))
        {
            select.Parameters.AddWithValue("type_key", NpgsqlDbType.Varchar, portalTypeKey);
            select.Parameters.AddWithValue("range_start", NpgsqlDbType.Date, rangeStart);
            select.Parameters.AddWithValue("range_end", NpgsqlDbType.Date, rangeEnd);
            await using var reader = await select.ExecuteReaderAsync(cancellationToken);
            while (await reader.ReadAsync(cancellationToken))
            {
                var key = reader.GetString(1);
                if (!seen.Contains(key)) missing.Add((reader.GetInt32(0), key, reader.GetInt32(2)));
            }
        }

        const string tombstoneSql = """
            INSERT INTO public.invoices (
                logical_key, version_no, previous_version_id, invoice_from_address_id, invoice_to_address_id,
                portal_type_key, portal_type_name, document_number, ettn, issue_date, due_date,
                counterparty_name, counterparty_tax_id, scenario, invoice_type, currency, status,
                line_extension_amount, tax_exclusive_amount, tax_amount, tax_inclusive_amount, payable_amount,
                notes, is_medication_invoice, was_it_saved, is_deleted, deleted_at,
                import_range_start, import_range_end, source_fingerprint, source_list_data, source_metadata, source_html)
            SELECT logical_key, @version_no, record_id, invoice_from_address_id, invoice_to_address_id,
                portal_type_key, portal_type_name, document_number, ettn, issue_date, due_date,
                counterparty_name, counterparty_tax_id, scenario, invoice_type, currency, status,
                line_extension_amount, tax_exclusive_amount, tax_amount, tax_inclusive_amount, payable_amount,
                notes, is_medication_invoice, was_it_saved, true, now(),
                @range_start, @range_end, @fingerprint, source_list_data, source_metadata, source_html
            FROM public.invoices WHERE record_id = @record_id AND is_deleted = false
            RETURNING record_id;
            """;
        var count = 0;
        foreach (var row in missing)
        {
            await using var tombstone = pharmacyApp.Infrastructure.DatabaseCommand.Create(tombstoneSql, connection, transaction);
            tombstone.Parameters.AddWithValue("version_no", NpgsqlDbType.Integer, row.VersionNo + 1);
            tombstone.Parameters.AddWithValue("range_start", NpgsqlDbType.Date, rangeStart);
            tombstone.Parameters.AddWithValue("range_end", NpgsqlDbType.Date, rangeEnd);
            tombstone.Parameters.AddWithValue("fingerprint", NpgsqlDbType.Char, Fingerprint($"deleted|{row.LogicalKey}|{row.VersionNo + 1}"));
            tombstone.Parameters.AddWithValue("record_id", NpgsqlDbType.Integer, row.RecordId);
            if (await tombstone.ExecuteScalarAsync(cancellationToken) is not null) count++;
        }
        await transaction.CommitAsync(cancellationToken);
        return count;
    }

    public static string BuildLogicalKey(string typeKey, string ettn, string documentNumber) =>
        $"{typeKey}|{(!string.IsNullOrWhiteSpace(ettn) ? ettn.Trim() : documentNumber.Trim())}";

    private static async Task<bool[]> DetectMedicationLinesAsync(
        NpgsqlConnection connection,
        NpgsqlTransaction transaction,
        IReadOnlyList<InvoiceDocumentLine> lines,
        CancellationToken cancellationToken)
    {
        var barcodes = lines.SelectMany(line => new[] { line.Barcode, line.ItemCode }
                .Concat(line.Values.Values))
            .SelectMany(value => System.Text.RegularExpressions.Regex.Matches(value ?? string.Empty, "(?<!\\d)\\d{8,14}(?!\\d)").Select(match => match.Value))
            .Distinct(StringComparer.Ordinal).ToArray();
        var names = lines.SelectMany(line => new[] { line.Name, line.Description })
            .Where(value => !string.IsNullOrWhiteSpace(value)).Select(value => value.Trim()).Distinct(StringComparer.OrdinalIgnoreCase).ToArray();
        const string sql = """
            SELECT COALESCE(array_agg(DISTINCT barcode) FILTER (WHERE barcode IS NOT NULL), ARRAY[]::varchar[]),
                   COALESCE(array_agg(DISTINCT upper(medicine_name)) FILTER (WHERE medicine_name IS NOT NULL), ARRAY[]::text[]),
                   COALESCE(array_agg(DISTINCT upper(old_name)) FILTER (WHERE old_name IS NOT NULL), ARRAY[]::text[]),
                   COALESCE(array_agg(DISTINCT upper(brand_name)) FILTER (WHERE brand_name IS NOT NULL), ARRAY[]::text[])
            FROM public.barcode
            WHERE barcode = ANY(@barcodes)
               OR ('0' || barcode) = ANY(@barcodes)
               OR upper(medicine_name) = ANY(@names)
               OR upper(old_name) = ANY(@names)
               OR EXISTS (
                    SELECT 1 FROM unnest(@names) AS invoice_name
                    WHERE length(trim(medicine_name)) >= 5
                      AND strpos(invoice_name, upper(trim(medicine_name))) > 0)
               OR EXISTS (
                    SELECT 1 FROM unnest(@names) AS invoice_name
                    WHERE length(trim(old_name)) >= 5
                      AND strpos(invoice_name, upper(trim(old_name))) > 0)
               OR EXISTS (
                    SELECT 1 FROM unnest(@names) AS invoice_name
                    WHERE length(split_part(trim(medicine_name), ' ', 1)) >= 4
                      AND split_part(invoice_name, ' ', 1) = upper(split_part(trim(medicine_name), ' ', 1)))
               OR EXISTS (
                    SELECT 1 FROM unnest(@names) AS invoice_name
                    WHERE length(split_part(trim(old_name), ' ', 1)) >= 4
                      AND split_part(invoice_name, ' ', 1) = upper(split_part(trim(old_name), ' ', 1)))
               OR EXISTS (
                    SELECT 1 FROM unnest(@names) AS invoice_name
                    WHERE length(split_part(trim(brand_name), ' ', 1)) >= 4
                      AND split_part(invoice_name, ' ', 1) = upper(split_part(trim(brand_name), ' ', 1)));
            """;
        await using var command = pharmacyApp.Infrastructure.DatabaseCommand.Create(sql, connection, transaction);
        command.Parameters.AddWithValue("barcodes", NpgsqlDbType.Array | NpgsqlDbType.Varchar, barcodes);
        command.Parameters.AddWithValue("names", NpgsqlDbType.Array | NpgsqlDbType.Text, names.Select(value => value.ToUpperInvariant()).ToArray());
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        await reader.ReadAsync(cancellationToken);
        var matchedBarcodes = reader.GetFieldValue<string[]>(0).ToHashSet(StringComparer.Ordinal);
        var matchedNames = reader.GetFieldValue<string[]>(1)
            .Concat(reader.GetFieldValue<string[]>(2))
            .Concat(reader.GetFieldValue<string[]>(3))
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
        return lines.Select(line =>
            new[] { line.Barcode, line.ItemCode }.Any(value => matchedBarcodes.Contains(value) || matchedBarcodes.Contains(value.TrimStart('0')))
            || new[] { line.Name, line.Description }.Any(value =>
                matchedNames.Any(name => name.Length >= 5 && (
                    value.Contains(name, StringComparison.OrdinalIgnoreCase)
                    || FirstToken(value).Equals(FirstToken(name), StringComparison.OrdinalIgnoreCase))))
            || InvoiceMedicationClassifier.HasPharmacyPricingFields(line.Values.Keys)
            || InvoiceMedicationClassifier.HasItsTraceabilityData(line.Values.Values)
            || line.Values.Values.Any(value => System.Text.RegularExpressions.Regex.Matches(value ?? string.Empty, "(?<!\\d)\\d{8,14}(?!\\d)")
                .Any(match => matchedBarcodes.Contains(match.Value) || matchedBarcodes.Contains(match.Value.TrimStart('0'))))).ToArray();
    }

    private static string FirstToken(string value) => value.Trim().Split(' ', StringSplitOptions.RemoveEmptyEntries).FirstOrDefault() ?? string.Empty;

    private static async Task<int> UpsertAddressAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, InvoiceParty party, CancellationToken cancellationToken)
    {
        var json = JsonSerializer.Serialize(party.Identifiers);
        var hash = Fingerprint(party);
        const string sql = """
            INSERT INTO public.addresses (party_name, address_text, phone, fax, email, website, tax_office,
                vkn, tckn, mersis_no, trade_registry_no, gln, identifiers, source_hash)
            VALUES (@name, @address, @phone, @fax, @email, @website, @tax_office,
                @vkn, @tckn, @mersis, @registry, @gln, @identifiers, @hash)
            ON CONFLICT (source_hash) DO UPDATE SET source_hash = EXCLUDED.source_hash
            RETURNING record_id;
            """;
        await using var command = pharmacyApp.Infrastructure.DatabaseCommand.Create(sql, connection, transaction);
        command.Parameters.AddWithValue("name", party.Name); command.Parameters.AddWithValue("address", party.Address);
        command.Parameters.AddWithValue("phone", party.Phone); command.Parameters.AddWithValue("fax", party.Fax);
