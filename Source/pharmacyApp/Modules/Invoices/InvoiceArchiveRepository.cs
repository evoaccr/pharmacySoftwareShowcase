    public async Task EnsureSchemaAsync(CancellationToken cancellationToken = default)
    {
        if (!DatabaseConnectionSettingsStore.Current.AllowSchemaChanges) return;
        await using var connection = DatabaseConnectionSettingsStore.CreateConnection();
        await connection.OpenAsync(cancellationToken);
        await using var command = pharmacyApp.Infrastructure.DatabaseCommand.Create(EnsureSchemaSql, connection);
        await command.ExecuteNonQueryAsync(cancellationToken);
    }

    public async Task<InvoiceArchiveSaveResult> SaveAsync(
        EczaciKartInvoiceDocument document,
        DateOnly rangeStart,
        DateOnly rangeEnd,
        bool forceNewVersion = false,
        CancellationToken cancellationToken = default)
    {
        await using var connection = DatabaseConnectionSettingsStore.CreateConnection();
        await connection.OpenAsync(cancellationToken);
        await using var transaction = await connection.BeginTransactionAsync(cancellationToken);
        if (DatabaseConnectionSettingsStore.Current.AllowSchemaChanges)
        await using (var schema = pharmacyApp.Infrastructure.DatabaseCommand.Create(EnsureSchemaSql, connection, transaction))
            await schema.ExecuteNonQueryAsync(cancellationToken);

        var medicationLines = await DetectMedicationLinesAsync(connection, transaction, document.Lines, cancellationToken);
        var isMedication = medicationLines.Any(value => value);
        var fromId = await UpsertAddressAsync(connection, transaction, document.InvoiceFrom, cancellationToken);
        var toId = await UpsertAddressAsync(connection, transaction, document.InvoiceTo, cancellationToken);
        var logicalKey = BuildLogicalKey(document.ListItem.TypeKey, document.Ettn, document.InvoiceNumber);
        var fingerprint = Fingerprint(new
        {
            document.ListItem,
            document.InvoiceFrom, document.InvoiceTo, document.InvoiceNumber, document.Ettn,
            document.IssueDate, document.DueDate, document.Scenario, document.InvoiceType, document.Currency,
            document.LineExtensionAmount, document.TaxExclusiveAmount, document.TaxAmount,
            document.TaxInclusiveAmount, document.PayableAmount, document.Notes, document.Metadata,
            document.Lines, medicationLines
        });

        var latest = await ReadLatestAsync(connection, transaction, logicalKey, cancellationToken);
        if (!forceNewVersion && latest is { IsDeleted: false } && latest.Fingerprint == fingerprint)
        {
            await transaction.CommitAsync(cancellationToken);
            return new InvoiceArchiveSaveResult(InvoiceArchiveSaveKind.Unchanged, latest.RecordId, isMedication);
        }

        var version = (latest?.VersionNo ?? 0) + 1;
        const string insertSql = """
            INSERT INTO public.invoices (
                logical_key, version_no, previous_version_id, invoice_from_address_id, invoice_to_address_id,
                portal_type_key, portal_type_name, document_number, ettn, issue_date, due_date,
                counterparty_name, counterparty_tax_id, scenario, invoice_type, currency, status,
                line_extension_amount, tax_exclusive_amount, tax_amount, tax_inclusive_amount, payable_amount,
                notes, is_medication_invoice, was_it_saved, import_range_start, import_range_end,
                source_fingerprint, source_list_data, source_metadata, source_html)
            VALUES (
                @logical_key, @version_no, @previous_version_id, @from_id, @to_id,
                @portal_type_key, @portal_type_name, @document_number, @ettn, @issue_date, @due_date,
                @counterparty_name, @counterparty_tax_id, @scenario, @invoice_type, @currency, @status,
                @line_extension_amount, @tax_exclusive_amount, @tax_amount, @tax_inclusive_amount, @payable_amount,
                @notes, @is_medication, @was_it_saved, @range_start, @range_end,
                @fingerprint, @list_data, @metadata, @source_html)
            RETURNING record_id;
            """;
        await using var insert = pharmacyApp.Infrastructure.DatabaseCommand.Create(insertSql, connection, transaction);
        insert.Parameters.AddWithValue("logical_key", NpgsqlDbType.Text, logicalKey);
        insert.Parameters.AddWithValue("version_no", NpgsqlDbType.Integer, version);
        AddNullable(insert, "previous_version_id", NpgsqlDbType.Integer, latest?.RecordId);
        insert.Parameters.AddWithValue("from_id", NpgsqlDbType.Integer, fromId);
        insert.Parameters.AddWithValue("to_id", NpgsqlDbType.Integer, toId);
        AddDocumentParameters(insert, document, isMedication, rangeStart, rangeEnd, fingerprint);
        var recordId = Convert.ToInt32(await insert.ExecuteScalarAsync(cancellationToken));

        for (var index = 0; index < document.Lines.Count; index++)
            await InsertLineAsync(connection, transaction, recordId, document.Lines[index], medicationLines[index], cancellationToken);

        await transaction.CommitAsync(cancellationToken);
        return new InvoiceArchiveSaveResult(
            latest is null ? InvoiceArchiveSaveKind.Inserted : InvoiceArchiveSaveKind.Versioned,
            recordId,
            isMedication);
    }

    public async Task<IReadOnlySet<string>> ReadExistingLogicalKeysAsync(
        IEnumerable<EczaciKartInvoiceItem> items,
        CancellationToken cancellationToken = default)
    {
        var keys = items.Select(item => BuildLogicalKey(item.TypeKey, item.Ettn, item.DocumentNumber))
            .Distinct(StringComparer.Ordinal).ToArray();
        if (keys.Length == 0) return new HashSet<string>(StringComparer.Ordinal);
        await using var connection = DatabaseConnectionSettingsStore.CreateConnection();
        await connection.OpenAsync(cancellationToken);
        await using var command = pharmacyApp.Infrastructure.DatabaseCommand.Create(
            "SELECT DISTINCT logical_key FROM public.invoices WHERE logical_key = ANY(@keys) AND is_deleted=false", connection);
        command.Parameters.AddWithValue("keys", NpgsqlDbType.Array | NpgsqlDbType.Text, keys);
        var result = new HashSet<string>(StringComparer.Ordinal);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken)) result.Add(reader.GetString(0));
        return result;
    }

    public async Task<IReadOnlyList<StoredInvoiceRow>> LoadInvoicesAsync(
        string? typeKey, DateOnly? startDate, DateOnly? endDate, string? search,
        CancellationToken cancellationToken = default)
    {
        await EnsureSchemaAsync(cancellationToken);
        await using var connection = DatabaseConnectionSettingsStore.CreateConnection();
        await connection.OpenAsync(cancellationToken);
        const string sql = """
            SELECT record_id, portal_type_name, document_number, ettn, issue_date,
                   counterparty_name, counterparty_tax_id, scenario, invoice_type,
                   payable_amount, currency, status, is_medication_invoice, was_it_saved,
                   is_deleted, version_no, imported_at
            FROM public.invoices
            WHERE (@type_key IS NULL OR portal_type_key=@type_key)
              AND (@start_date IS NULL OR issue_date>=@start_date)
              AND (@end_date IS NULL OR issue_date<=@end_date)
              AND (@search IS NULL OR document_number ILIKE @search OR ettn ILIKE @search
                   OR counterparty_name ILIKE @search OR counterparty_tax_id ILIKE @search)
            ORDER BY issue_date DESC NULLS LAST, record_id DESC;
            """;
        await using var command = pharmacyApp.Infrastructure.DatabaseCommand.Create(sql, connection);
        AddNullable(command, "type_key", NpgsqlDbType.Varchar, string.IsNullOrWhiteSpace(typeKey) ? null : typeKey);
        AddNullable(command, "start_date", NpgsqlDbType.Date, startDate);
        AddNullable(command, "end_date", NpgsqlDbType.Date, endDate);
        AddNullable(command, "search", NpgsqlDbType.Text, string.IsNullOrWhiteSpace(search) ? null : $"%{search.Trim()}%");
        var rows = new List<StoredInvoiceRow>();
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
            rows.Add(new StoredInvoiceRow(
                reader.GetInt32(0), reader.GetString(1), reader.GetString(2), reader.GetString(3),
                reader.IsDBNull(4) ? null : reader.GetFieldValue<DateOnly>(4), reader.GetString(5), reader.GetString(6),
                reader.GetString(7), reader.GetString(8), reader.IsDBNull(9) ? null : reader.GetDecimal(9),
                reader.GetString(10), reader.GetString(11), reader.GetBoolean(12),
                reader.IsDBNull(13) ? null : reader.GetBoolean(13), reader.GetBoolean(14), reader.GetInt32(15),
                reader.GetFieldValue<DateTimeOffset>(16)));
        return rows;
    }

