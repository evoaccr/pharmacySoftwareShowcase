    private static async Task<LatestInvoice?> ReadLatestAsync(NpgsqlConnection connection, NpgsqlTransaction transaction, string logicalKey, CancellationToken cancellationToken)
    {
        await using var command = pharmacyApp.Infrastructure.DatabaseCommand.Create("SELECT record_id, version_no, source_fingerprint, is_deleted FROM public.invoices WHERE logical_key=@key ORDER BY version_no DESC LIMIT 1", connection, transaction);
        command.Parameters.AddWithValue("key", logicalKey);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        return await reader.ReadAsync(cancellationToken) ? new LatestInvoice(reader.GetInt32(0), reader.GetInt32(1), reader.GetString(2), reader.GetBoolean(3)) : null;
    }

    private static void AddNullable(NpgsqlCommand command, string name, NpgsqlDbType type, object? value) =>
        command.Parameters.Add(new NpgsqlParameter(name, type) { Value = value ?? DBNull.Value });

    private static string Fingerprint(object value) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(JsonSerializer.Serialize(value)))).ToLowerInvariant();

